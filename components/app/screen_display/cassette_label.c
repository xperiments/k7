/*
 * cassette_label.c - see cassette_label.h and docs/specs/label-templates.md §6.
 *
 * One container the size of the design's space, inside the print, and one object per prim:
 * a styled box for a rect, an lv_label for a text. The container is what makes the design's
 * coordinates mean something at both Card layouts - its children are placed in 748x359 space,
 * and the print decides where that space is on the panel.
 *
 * The design is rebuilt only when the selected template changes, which for a given Track
 * never happens: a Track change rewrites the eleven texts and nothing else. That is why the
 * play path costs a handful of lv_label_set_text calls and no allocation.
 */
#include "cassette_label.h"

#include "label.h"
#include "label_fonts.h"
#include "screen_caps.h"

#include <string.h>

#include "esp_log.h"

LV_FONT_DECLARE(jura_20);
LV_FONT_DECLARE(jura_28);
LV_FONT_DECLARE(jura_36);
LV_FONT_DECLARE(archivo_narrow_600_32);
LV_FONT_DECLARE(barlow_condensed_700_78);
LV_FONT_DECLARE(ibm_plex_mono_500_18);

static const char *TAG = "label";

/* The compiled faces, in the order assets/labels/vocabulary.json declares them. label_fonts.h is
 * generated by the packer from that file, so a missing symbol here is a compile error rather
 * than a label that quietly prints in the wrong face. */
static const lv_font_t *const k_label_font[LABEL_FONT_COUNT] = {
    &jura_20,
    &jura_28,
    &jura_36,
    &archivo_narrow_600_32,
    &barlow_condensed_700_78,
    &ibm_plex_mono_500_18,
};

typedef struct {
    lv_obj_t   *obj;
    const char *slot;   /* NULL for a static text: its words are the design's */
    uint8_t     max;    /* the characters the design allows for that slot */
    bool        rotated;/* the pivot sits on the label's centre, which the text moves */
} text_node_t;

static label_sheet_t *s_sheet;
static lv_obj_t      *s_root;
static uint16_t       s_template = UINT16_MAX;
static text_node_t    s_text[LABEL_PRIM_MAX];
static uint16_t       s_text_count;
static bool           s_full;
static bool           s_has_canvas;
static uint32_t       s_canvas;

static lv_color_t fill_colour(const label_inks_t *inks, uint8_t fill, uint32_t literal)
{
    switch (fill) {
    case LABEL_FILL_PAPER: return lv_color_hex(inks->paper);
    case LABEL_FILL_INK: return lv_color_hex(inks->ink);
    case LABEL_FILL_RULE: return lv_color_hex(inks->rule);
    case LABEL_FILL_BAND0: return lv_color_hex(inks->band[0]);
    case LABEL_FILL_BAND1: return lv_color_hex(inks->band[1]);
    case LABEL_FILL_BAND2: return lv_color_hex(inks->band[2]);
    case LABEL_FILL_BAND3: return lv_color_hex(inks->band[3]);
    case LABEL_FILL_BAND4: return lv_color_hex(inks->band[4]);
    case LABEL_FILL_BAND5: return lv_color_hex(inks->band[5]);
    case LABEL_FILL_BAND6: return lv_color_hex(inks->band[6]);
    case LABEL_FILL_BAND7: return lv_color_hex(inks->band[7]);
    default: return lv_color_hex(literal);
    }
}

/* A rect is one box: no border, no padding, no scroll, and the design's radius. A rotation
 * turns it about its own centre, which is what the editor's preview shows. */
static lv_obj_t *rect_create(lv_obj_t *parent, const label_prim_t *p, lv_color_t colour)
{
    lv_obj_t *o = lv_obj_create(parent);
    lv_obj_remove_style_all(o);
    lv_obj_set_clickable(o, false);
    lv_obj_set_scrollable(o, false);
    lv_obj_set_pos(o, p->x, p->y);
    lv_obj_set_size(o, p->w, p->h);
    lv_obj_set_style_bg_color(o, colour, 0);
    lv_obj_set_style_bg_opa(o, LV_OPA_COVER, 0);
    lv_obj_set_style_radius(o, p->r, 0);
    if (p->rot10) {
        lv_obj_set_style_transform_pivot_x(o, p->w / 2, 0);
        lv_obj_set_style_transform_pivot_y(o, p->h / 2, 0);
        lv_obj_set_style_transform_rotation(o, p->rot10, 0);
    }
    return o;
}

/* A text is one label of the design's width; it wraps inside it, exactly as the editor's
 * preview does, and its height follows from what it says. */
static lv_obj_t *text_create(lv_obj_t *parent, const label_prim_t *p, lv_color_t colour,
                             uint8_t font_index, const char *initial)
{
    lv_obj_t *o = lv_label_create(parent);
    lv_obj_set_clickable(o, false);
    lv_obj_set_pos(o, p->x, p->y);
    lv_obj_set_width(o, p->w);
    lv_label_set_long_mode(o, LV_LABEL_LONG_WRAP);
    lv_obj_set_style_text_font(o, k_label_font[font_index], 0);
    lv_obj_set_style_text_color(o, colour, 0);
    lv_obj_set_style_text_align(o, p->align == LABEL_ALIGN_RIGHT  ? LV_TEXT_ALIGN_RIGHT
                                   : p->align == LABEL_ALIGN_CENTER ? LV_TEXT_ALIGN_CENTER
                                                                    : LV_TEXT_ALIGN_LEFT, 0);
    if (initial) lv_label_set_text(o, initial);
    if (p->rot10) {
        /* The pivot is the label's centre, and the label's height is only known once it has
         * said something: set the text, lay it out, then pin the pivot - as genC does. */
        lv_obj_update_layout(o);
        lv_obj_set_style_transform_pivot_x(o, lv_obj_get_width(o) / 2, 0);
        lv_obj_set_style_transform_pivot_y(o, lv_obj_get_height(o) / 2, 0);
        lv_obj_set_style_transform_rotation(o, p->rot10, 0);
    }
    return o;
}

/* The design's slot record for `name`, so the text knows how many characters it may print. */
static uint8_t slot_max(uint16_t t, const char *name)
{
    uint16_t n = label_slot_count(s_sheet, t);
    for (uint16_t i = 0; i < n; i++) {
        label_slot_t slot;
        if (label_slot_at(s_sheet, t, i, &slot) && strcmp(slot.name, name) == 0) return slot.max;
    }
    return (uint8_t)LABEL_VALUE_MAX;
}

static void destroy_nodes(void)
{
    if (s_root) lv_obj_clean(s_root);
    s_text_count = 0;
    memset(s_text, 0, sizeof s_text);
}

static void build(uint16_t t)
{
    destroy_nodes();

    const label_inks_t inks = label_inks(s_sheet, t);
    const uint16_t n = label_prim_count(s_sheet, t);
    s_canvas = 0;
    s_has_canvas = label_canvas(s_sheet, t, &s_canvas);

    for (uint16_t i = 0; i < n; i++) {
        label_prim_t p;
        if (!label_prim_at(s_sheet, t, i, &p)) continue;

        const lv_color_t colour = fill_colour(&inks, p.fill, p.literal);
        const uint8_t font_index = label_font(s_sheet, t, p.font);

        if (p.kind == LABEL_RECT) {
            rect_create(s_root, &p, colour);
            continue;
        }

        const char *text = label_prim_text(s_sheet, t, i);
        const bool is_slot = (p.kind == LABEL_TEXT_SLOT);
        lv_obj_t *o = text_create(s_root, &p, colour, font_index,
                                  is_slot ? "" : (text ? text : ""));
        if (!o) continue;

        if (s_text_count < LABEL_PRIM_MAX) {
            text_node_t *node = &s_text[s_text_count++];
            node->obj = o;
            node->slot = is_slot ? text : NULL;
            node->max = node->slot ? slot_max(t, node->slot) : 0;
            node->rotated = p.rot10 != 0;
        }
    }

    ESP_LOGI(TAG, "design %u of %u: %s", (unsigned)t, (unsigned)label_templates(s_sheet),
             label_template_name(s_sheet, t));
}

static void set_texts(const label_values_t *values)
{
    char buf[LABEL_VALUE_MAX + 1];
    for (uint16_t i = 0; i < s_text_count; i++) {
        text_node_t *node = &s_text[i];
        if (!node->slot) continue;
        const char *value = values ? label_values_get(values, node->slot) : "";
        label_cut(value, node->max, buf, sizeof buf);
        lv_label_set_text(node->obj, buf);
        if (node->rotated) {
            /* The words moved, so the centre the rotation turns about has moved with them. */
            lv_obj_update_layout(node->obj);
            lv_obj_set_style_transform_pivot_x(node->obj, lv_obj_get_width(node->obj) / 2, 0);
            lv_obj_set_style_transform_pivot_y(node->obj, lv_obj_get_height(node->obj) / 2, 0);
        }
    }
}

void cassette_label_create(lv_obj_t *print, const uint8_t *sheet, size_t sheet_size)
{
    if (s_root || !print) return;

    /* A board with no cover has no white page and no print: there is nothing to print on. */
    if (!screen_caps()->cover) return;

    char why[96];
    if (!sheet || sheet_size == 0) return;
    if (label_open_why(sheet, sheet_size, LABEL_FONT_COUNT, &s_sheet, why, sizeof why) !=
        LABEL_OK) {
        ESP_LOGE(TAG, "the label sheet did not open (%s); the print keeps its flat fill", why);
        s_sheet = NULL;
        return;
    }

    s_root = lv_obj_create(print);
    lv_obj_remove_style_all(s_root);
    lv_obj_set_style_bg_opa(s_root, LV_OPA_TRANSP, 0);
    lv_obj_set_style_border_width(s_root, 0, 0);
    lv_obj_set_style_pad_all(s_root, 0, 0);
    lv_obj_set_scrollable(s_root, false);
    lv_obj_set_clickable(s_root, false);
    lv_obj_set_pos(s_root, 0, 0);
    lv_obj_set_size(s_root, LABEL_SPACE_W, LABEL_SPACE_H);
    lv_obj_set_hidden(s_root, true);

    ESP_LOGI(TAG, "label sheet: %u designs", (unsigned)label_templates(s_sheet));
}

void cassette_label_set_pose(bool full)
{
    s_full = full;
    if (s_root) lv_obj_set_hidden(s_root, !full);
}

void cassette_label_update(uint32_t ink_seed, const label_values_t *values)
{
    if (!s_sheet || !s_root) return;

    const uint16_t t = label_pick(s_sheet, ink_seed);
    if (t != s_template) {
        s_template = t;
        build(t);
    }
    set_texts(values);
}

uint16_t cassette_label_templates(void)
{
    return s_sheet ? label_templates(s_sheet) : 0;
}

bool cassette_label_canvas(uint32_t *rgb)
{
    if (!s_has_canvas || !rgb) return false;
    *rgb = s_canvas;
    return true;
}

#if CONFIG_APP_UI_RENDER_BENCH
void cassette_label_bench_fill(void)
{
    for (uint16_t i = 0; i < s_text_count; i++) {
        if (!s_text[i].slot || !s_text[i].obj) continue;
        char buf[LABEL_VALUE_MAX + 1];
        label_cut("El Sol De Verano", s_text[i].max, buf, sizeof buf);
        lv_label_set_text(s_text[i].obj, buf);
    }
}

void cassette_label_bench_texts(void)
{
    for (uint16_t i = 0; i < s_text_count; i++) {
        if (s_text[i].obj) lv_obj_invalidate(s_text[i].obj);
    }
}
#endif
