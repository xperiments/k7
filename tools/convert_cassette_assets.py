#!/usr/bin/env python3
"""Turn the cassette art into what the firmware can blit.

    python3 tools/convert_cassette_assets.py            # writes label_cover.{h,bin}, header_logo.{h,bin} and cover.{jpg,h}
    python3 tools/convert_cassette_assets.py --check    # only validates and reports

The hubs are no longer exported: components/app/screen_display/cassette_view.c draws them
as a static rim with a divided circle turning inside it, so there is no hub blob to
build. assets/hub/NNN.png stays in the tree as the art the drawn geometry was derived
from, and docs/research/hub-drawn-vs-blitted.md records why the blit went away.

The label cover is assets/labels/k7logo.png: a full-bleed cover at the panel's 800x480.
A cover with transparency (a tape window) is exported as RGB565A8 (RGB565 plus an A8
plane), so the reels show through it; an opaque cover is exported as RGB565. This is a
static image drawn once when the cover is shown; it does not carry the hub path's 25 Hz
blend cost.

The Artwork backdrop is assets/labels/cover.jpg: the cassette case at the panel's
800x480. It is opaque, so it is not converted to a pixel blob; the tool validates it,
copies it into the component and writes a header with the embedded symbols. The
firmware decodes it once at start into PSRAM and the Track artwork is drawn into its
window. Keeping the JPEG costs 45 KB of flash instead of the 768 KB a raw RGB565 copy
would take, and the TJpgDec decoder is already in the image.

The K7 mark in the controls header is assets/labels/k7b.png: greyscale art with an alpha
plane. Only the alpha is kept, at one byte per pixel (A8), so the firmware can tint the
same blob with COL_PRIMARY on the line-art page and black on the white one. That is much
smaller than RGB565A8 and the tint is one style property.

The label blob is the label's pixels. The header wraps it in an lv_image_dsc_t
descriptor and carries the size. It is embedded by
components/app/screen_display/CMakeLists.txt and rebuilt by this tool; do not edit it by
hand.

The label keeps its alpha when it has one: a transparent tape window is the point of
that art.

Requires Pillow (`pip install pillow`), which the project's documentation lists for
the host tooling.
"""
import argparse
import os
import shutil
import struct
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("needs Pillow: pip install pillow")

LABEL_SRC = "assets/labels/k7logo.png"
LABEL_OUT_BIN = "components/app/screen_display/assets/label_cover.bin"
LABEL_OUT_HDR = "components/app/screen_display/include/label_cover.h"

# The K7 mark in the controls header. Greyscale with an alpha plane; only the alpha is
# exported, as A8, so the firmware tints it with the page's ink.
LOGO_SRC = "assets/labels/k7b.png"
LOGO_OUT_BIN = "components/app/screen_display/assets/header_logo.bin"
LOGO_OUT_HDR = "components/app/screen_display/include/header_logo.h"
LOGO_STRIDE_ALIGN = 4

# The Artwork level's backdrop: the cassette case, embedded as a JPEG and decoded once at
# start. It is opaque and exactly the panel's size, so it is copied, not converted.
CASE_SRC = "assets/labels/cover.jpg"
CASE_OUT_BIN = "components/app/screen_display/assets/cover.jpg"
CASE_OUT_HDR = "components/app/screen_display/include/cover_jpg.h"
CASE_W = 800
CASE_H = 480


def rgb565(im):
    """Opaque RGB565 rows, little-endian, the stride the descriptors declare."""
    w, h = im.size
    px = im.load()
    data = bytearray(w * h * 2)
    i = 0
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            struct.pack_into("<H", data, i, ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
            i += 2
    return bytes(data)


def rgb565a8(im):
    """RGB565 rows followed by the A8 plane, the layout the engine's RGB565A8 expects."""
    w, h = im.size
    px = im.load()
    rgb = bytearray(w * h * 2)
    a8 = bytearray(w * h)
    p = 0
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            struct.pack_into("<H", rgb, p * 2,
                             ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
            a8[p] = a
            p += 1
    return bytes(rgb + a8)


def a8(im):
    """The alpha plane alone, padded to LVGL's stride alignment, for an A8 image."""
    w, h = im.size
    stride = (w + LOGO_STRIDE_ALIGN - 1) & ~(LOGO_STRIDE_ALIGN - 1)
    alpha = im.getchannel("A").tobytes()
    pad = b"\x00" * (stride - w)
    data = bytearray()
    for y in range(h):
        data += alpha[y * w:(y + 1) * w] + pad
    return bytes(data), stride


def label_header_text(w, h, opaque):
    bpp = 2 if opaque else 3
    cf = "LV_COLOR_FORMAT_RGB565" if opaque else "LV_COLOR_FORMAT_RGB565A8"
    out = []
    out.append("/* Generated by tools/convert_cassette_assets.py from %s." % LABEL_SRC)
    out.append(" * Do not edit: re-run the tool after changing the art. */")
    out.append("#pragma once")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append('#include "lvgl.h"')
    out.append("")
    out.append("#define LABEL_COVER_W %d" % w)
    out.append("#define LABEL_COVER_H %d" % h)
    out.append("#define LABEL_COVER_BYTES (LABEL_COVER_W * LABEL_COVER_H * %d)" % bpp)
    out.append("")
    if opaque:
        out.append("/* Opaque RGB565, with no alpha plane. EMBED_FILES puts the blob in the")
        out.append(" * image under this name. */")
    else:
        out.append("/* RGB565 followed by the A8 plane: the cover has transparent pixels, so")
        out.append(" * the reels show through them. EMBED_FILES puts the blob in the image")
        out.append(" * under this name. */")
    out.append('extern const uint8_t label_cover_bin_start[] asm("_binary_label_cover_bin_start");')
    out.append("")
    out.append("static const lv_image_dsc_t k_label_cover = {")
    out.append("    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = %s," % cf)
    out.append("                .w = LABEL_COVER_W, .h = LABEL_COVER_H,")
    out.append("                .stride = LABEL_COVER_W * 2 },")
    out.append("    .data_size = LABEL_COVER_BYTES,")
    out.append("    .data = label_cover_bin_start,")
    out.append("};")
    out.append("")
    return "\n".join(out)


def is_opaque(im):
    """True when every pixel has alpha 255, so the A8 plane would be all 255s."""
    return im.getchannel("A").getextrema() == (255, 255)


def logo_header_text(w, h, stride):
    out = []
    out.append("/* Generated by tools/convert_cassette_assets.py from %s." % LOGO_SRC)
    out.append(" * Do not edit: re-run the tool after changing the art. */")
    out.append("#pragma once")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append('#include "lvgl.h"')
    out.append("")
    out.append("#define HEADER_LOGO_W %d" % w)
    out.append("#define HEADER_LOGO_H %d" % h)
    out.append("#define HEADER_LOGO_STRIDE %d" % stride)
    out.append("#define HEADER_LOGO_BYTES (HEADER_LOGO_STRIDE * HEADER_LOGO_H)")
    out.append("")
    out.append("/* The K7 mark as an A8 mask: the firmware tints it with the page's ink and")
    out.append(" * EMBED_FILES puts the blob in the image under this name. */")
    out.append('extern const uint8_t header_logo_bin_start[] asm("_binary_header_logo_bin_start");')
    out.append("")
    out.append("static const lv_image_dsc_t k_header_logo = {")
    out.append("    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8,")
    out.append("                .w = HEADER_LOGO_W, .h = HEADER_LOGO_H,")
    out.append("                .stride = HEADER_LOGO_STRIDE },")
    out.append("    .data_size = HEADER_LOGO_BYTES,")
    out.append("    .data = header_logo_bin_start,")
    out.append("};")
    out.append("")
    return "\n".join(out)


def case_header_text():
    out = []
    out.append("/* Generated by tools/convert_cassette_assets.py from %s." % CASE_SRC)
    out.append(" * Do not edit: re-run the tool after changing the art. */")
    out.append("#pragma once")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("#define COVER_JPG_W %d" % CASE_W)
    out.append("#define COVER_JPG_H %d" % CASE_H)
    out.append("")
    out.append("/* The Artwork backdrop, embedded as the original JPEG: the firmware decodes")
    out.append(" * it once at start into PSRAM. EMBED_FILES puts the bytes in the image under")
    out.append(" * these names. */")
    out.append('extern const uint8_t cover_jpg_start[] asm("_binary_cover_jpg_start");')
    out.append('extern const uint8_t cover_jpg_end[] asm("_binary_cover_jpg_end");')
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate and report, write nothing")
    args = ap.parse_args()

    if not os.path.exists(LABEL_SRC):
        sys.exit(f"missing label art: {LABEL_SRC}")
    label = Image.open(LABEL_SRC).convert("RGBA")
    label_opaque = is_opaque(label)
    label_blob = rgb565(label.convert("RGB")) if label_opaque else rgb565a8(label)
    print(f"label {label.size[0]}x{label.size[1]} from {LABEL_SRC}; "
          f"{'RGB565' if label_opaque else 'RGB565A8'} "
          f"{len(label_blob)} B ({len(label_blob) // 1024} KB)")

    if not os.path.exists(CASE_SRC):
        sys.exit(f"missing case art: {CASE_SRC}")
    case = Image.open(CASE_SRC)
    if case.size != (CASE_W, CASE_H):
        sys.exit(f"{CASE_SRC} is {case.size[0]}x{case.size[1]}, expected {CASE_W}x{CASE_H}")
    case_bytes = os.path.getsize(CASE_SRC)
    print(f"case {CASE_W}x{CASE_H} from {CASE_SRC}; JPEG {case_bytes} B "
          f"({case_bytes // 1024} KB)")

    if not os.path.exists(LOGO_SRC):
        sys.exit(f"missing header logo art: {LOGO_SRC}")
    logo = Image.open(LOGO_SRC).convert("RGBA")
    logo_blob, logo_stride = a8(logo)
    print(f"header logo {logo.size[0]}x{logo.size[1]} from {LOGO_SRC}; A8 "
          f"{len(logo_blob)} B ({len(logo_blob) // 1024} KB), stride {logo_stride}")

    if args.check:
        print("--check: nothing written")
        return

    with open(LABEL_OUT_BIN, "wb") as f:
        f.write(label_blob)
    print(f"wrote {LABEL_OUT_BIN}")

    with open(LABEL_OUT_HDR, "w") as f:
        f.write(label_header_text(*label.size, label_opaque))
    print(f"wrote {LABEL_OUT_HDR}")

    os.makedirs(os.path.dirname(CASE_OUT_BIN), exist_ok=True)
    shutil.copyfile(CASE_SRC, CASE_OUT_BIN)
    print(f"wrote {CASE_OUT_BIN}")

    with open(CASE_OUT_HDR, "w") as f:
        f.write(case_header_text())
    print(f"wrote {CASE_OUT_HDR}")

    with open(LOGO_OUT_BIN, "wb") as f:
        f.write(logo_blob)
    print(f"wrote {LOGO_OUT_BIN}")

    with open(LOGO_OUT_HDR, "w") as f:
        f.write(logo_header_text(*logo.size, logo_stride))
    print(f"wrote {LOGO_OUT_HDR}")


if __name__ == "__main__":
    main()
