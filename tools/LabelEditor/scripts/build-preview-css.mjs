/**
 * Build `src/preview/preview.css` from the App's own stylesheet.
 *
 * The editor's Preview draws the J-card with the App's renderer, so it has to draw it with
 * the App's stylesheet too. Copying the rules by hand is how the two cases drifted apart
 * once already, so the copy is made by this script: the App's `@layer components` block,
 * selector for selector, every selector nested under `.k7app-preview` so none of it can
 * reach the editor's panels or its canvas.
 *
 *   npm run preview:css        # write the file
 *   npm run preview:css -- --check   # fail when the file is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const APP = resolve(here, '../../../web/src/index.css');
const OUT = resolve(here, '../src/preview/preview.css');
const PREFIX = '.k7app-preview ';

const HEADER = `/*
 * The app's own case and shelf rules, scoped to the preview.
 *
 * This is the app's \`web/src/index.css\` components layer, selector for selector, with every
 * selector nested under \`.k7app-preview\` so none of it can reach the editor's panels or its
 * canvas. It is a copy on purpose: the preview draws the J-card with the app's renderer, so it
 * must draw it with the app's stylesheet too - a change to the App's look belongs here as it
 * stands. The only rules of the preview's own are the one at the end.
 *
 * Generated by \`npm run preview:css\`; edit \`web/src/index.css\`, not this file.
 */
@layer components {
`;

const TAIL = `
    /* The preview holds two cases and no row continuing past the fold, and its stage is
       narrower than the media page's: the shelf's edge fade would only dim them. */
    .k7app-preview .k7-shelf {
        -webkit-mask-image: none;
        mask-image: none;
    }
}
`;

/** Split a selector list on its top-level commas and nest each part. */
function scopeSelector(selector, indent) {
  const parts = [];
  let buffer = '';
  let parens = 0;
  for (const ch of selector) {
    if (ch === '(') parens += 1;
    else if (ch === ')') parens -= 1;
    if (ch === ',' && parens === 0) {
      parts.push(buffer);
      buffer = '';
      continue;
    }
    buffer += ch;
  }
  parts.push(buffer);
  const scoped = parts.map((part) => part.trim()).filter(Boolean).map((part) => PREFIX + part);
  return scoped.join(',\n' + indent);
}

/** The `@layer components` block's inner text. */
function componentsLayer(css) {
  const start = css.indexOf('@layer components {');
  if (start < 0) throw new Error('web/src/index.css has no @layer components block');
  let depth = 0;
  for (let i = start; i < css.length; i += 1) {
    if (css[i] === '{') depth += 1;
    else if (css[i] === '}') {
      depth -= 1;
      if (depth === 0) return css.slice(start + '@layer components {'.length, i);
    }
  }
  throw new Error('the @layer components block is not closed');
}

function scope(inner) {
  const out = [];
  let i = 0;
  const n = inner.length;
  while (i < n) {
    let j = i;
    while (j < n && ' \t\r\n'.includes(inner[j])) j += 1;
    if (inner.startsWith('/*', j)) {
      const end = inner.indexOf('*/', j) + 2;
      out.push(inner.slice(i, end));
      i = end;
      continue;
    }
    if (j >= n) {
      out.push(inner.slice(i));
      break;
    }
    if (inner[j] === '}') {
      out.push(inner.slice(i, j + 1));
      i = j + 1;
      continue;
    }
    let k = j;
    let quote = null;
    let parens = 0;
    while (k < n) {
      const ch = inner[k];
      if (quote) {
        if (ch === quote) quote = null;
      } else if (ch === '"' || ch === "'") {
        quote = ch;
      } else if (ch === '(') {
        parens += 1;
      } else if (ch === ')') {
        parens -= 1;
      } else if (parens === 0 && (ch === '{' || ch === ';')) {
        break;
      }
      k += 1;
    }
    const prelude = inner.slice(j, k);
    if (k < n && inner[k] === '{') {
      if (prelude.trimStart().startsWith('@')) {
        out.push(inner.slice(i, k + 1));
        i = k + 1;
        continue;
      }
      /* The whitespace before the selector (a comment's newline, usually) is kept as it
       * stands; only its last line's indent is repeated in front of a continuation. */
      const whitespace = inner.slice(i, j);
      const indent = /[ \t]*$/.exec(whitespace)?.[0] ?? '';
      out.push(whitespace + scopeSelector(prelude, indent) + ' {');
      i = k + 1;
      let depth = 1;
      let m = i;
      while (m < n && depth > 0) {
        if (inner[m] === '{') depth += 1;
        else if (inner[m] === '}') depth -= 1;
        m += 1;
      }
      out.push(inner.slice(i, m));
      i = m;
      continue;
    }
    out.push(inner.slice(i, k + 1));
    i = k + 1;
  }
  return out.join('');
}

const css = HEADER + scope(componentsLayer(readFileSync(APP, 'utf8'))) + TAIL;
const current = (() => {
  try {
    return readFileSync(OUT, 'utf8');
  } catch {
    return '';
  }
})();

if (process.argv.includes('--check')) {
  if (current !== css) {
    console.error('preview.css is stale: run `npm run preview:css`');
    process.exit(1);
  }
  console.log('preview.css follows web/src/index.css');
} else {
  writeFileSync(OUT, css);
  console.log('preview:css: wrote', OUT);
}
